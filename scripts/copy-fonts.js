'use strict';
// Copies the bundled widget fonts (SIL Open Font License, from the @fontsource packages) into
// src/renderer/fonts and writes fonts.css + fonts.json. Run after adding a font: `npm run fonts`.
const fs = require('fs');
const path = require('path');

const FONTS = [
  ['orbitron', 'Orbitron'], ['audiowide', 'Audiowide'], ['bebas-neue', 'Bebas Neue'], ['poppins', 'Poppins'],
  ['space-grotesk', 'Space Grotesk'], ['righteous', 'Righteous'], ['pacifico', 'Pacifico'], ['caveat', 'Caveat'],
  ['press-start-2p', 'Press Start 2P'], ['comfortaa', 'Comfortaa'], ['quicksand', 'Quicksand'], ['monoton', 'Monoton'],
  ['major-mono-display', 'Major Mono Display'], ['dancing-script', 'Dancing Script'], ['rajdhani', 'Rajdhani']
];
const root = path.join(__dirname, '..');
const out = path.join(root, 'src', 'renderer', 'fonts');
fs.mkdirSync(out, { recursive: true });
let css = '/* Bundled widget fonts. SIL Open Font License 1.1, see LICENSES.txt. Generated by scripts/copy-fonts.js */\n';
let licenses = '';
for (const [pkg, family] of FONTS) {
  const dir = path.join(root, 'node_modules', '@fontsource', pkg);
  for (const w of [300, 400, 700]) {
    const f = `${pkg}-latin-${w}-normal.woff2`;
    const src = path.join(dir, 'files', f);
    if (!fs.existsSync(src)) continue;
    fs.copyFileSync(src, path.join(out, f));
    css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:swap;src:url("${f}") format("woff2")}\n`;
  }
  licenses += `==== ${family} ====\n${fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8').trim()}\n\n`;
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.writeFileSync(path.join(out, 'fonts.json'), JSON.stringify(FONTS.map(([, f]) => f)));
fs.writeFileSync(path.join(out, 'LICENSES.txt'), licenses);
console.log('fonts:', FONTS.length, 'files:', fs.readdirSync(out).filter((f) => f.endsWith('.woff2')).length);
